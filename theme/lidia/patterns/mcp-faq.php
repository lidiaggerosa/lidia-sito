<details class="wp-block-details" open><summary>Che cos’è un server MCP?</summary><!-- wp:paragraph -->
<p>MCP è uno standard aperto che collega un assistente AI, come Claude o ChatGPT, ad altri strumenti. Il server MCP di Lidia è il collegamento tra il tuo assistente e Lidia.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Perché usare Lidia dentro il mio assistente AI?</summary><!-- wp:paragraph -->
<p>Perché un assistente generalista di AI non ha accesso ai database di fonti ufficiali e non ha un contesto giuridico coerente con le attività svolte dai professionisti legali. Con Lidia lavora su norme, giurisprudenza, prassi e pratiche reali, citando sempre le fonti di riferimento.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Come si richiama Lidia?</summary><!-- wp:paragraph -->
<p>Basta citarla nella richiesta, per esempio: «Lidia, svolgi una ricerca sugli orientamenti di legittimità in merito al licenziamento per giusta causa».</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quali funzioni di Lidia posso usare?</summary><!-- wp:paragraph -->
<p>Tutte: ricerca di normativa e giurisprudenza, domande sui documenti, workflow, pratiche e archivio.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quello che faccio nell’assistente resta su Lidia?</summary><!-- wp:paragraph -->
<p>Sì. Pratiche, documenti e note che salvi dall’assistente li ritrovi su Lidia.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Con quali assistenti AI funziona?</summary><!-- wp:paragraph -->
<p>Con Claude, ChatGPT e gli altri assistenti AI compatibili con MCP.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Con Lidia l’assistente smette di inventare le fonti?</summary><!-- wp:paragraph -->
<p>Le norme e le sentenze che arrivano da Lidia vengono dalla sua ricerca legale sulle fonti ufficiali, e sono sempre citate: puoi aprirle e controllarle una per una.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

